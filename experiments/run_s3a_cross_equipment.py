"""S3a: Cross-Equipment Generalization Experiment

Uses the existing equipment_types field in test_mil470a_88.jsonl
to group the 88 test items by equipment type (aircraft_engine / armored_vehicle / naval_power),
then evaluates StructStdRAG + 2 baselines on each subset to compare
performance differences across equipment types.

Logic:
- Read results/s1/per_item_outputs.jsonl (per-item x method answers generated by T1)
- Group by equipment_types field (one item may belong to multiple equipment types)
- For each group x method: compute Tuple-F1 / Hallucination Rate / Answer Coverage
- Output results/s3/s3a_cross_equipment.json and s3a_cross_equipment.md

Evidence: If StructStdRAG performs consistently across all three equipment types
(small std), this demonstrates good generalization of the method.
"""

from __future__ import annotations

import json
import sys
import re
from pathlib import Path
from collections import defaultdict

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.config import RESULTS_DIR, MAINTQA_DIR
from src.evaluation.metrics import tuple_f1, extract_answer_tuples, partial_match
from src.evaluation.statistical_test import bootstrap_ci
from src.utils.logger import get_logger

logger = get_logger("S3a")

NUMERIC_RE = re.compile(r"(\d+\.?\d*)\s*(mm|cm|m|kg|N|h|%|°)")
EQUIPMENT_LABELS = {
    "aircraft_engine": "Aircraft Engine",
    "armored_vehicle": "Armored Vehicle",
    "naval_power": "Naval Power",
}


def is_hallucinated(pred: str, retrieved: list[str]) -> bool:
    """Simplified hallucination check: whether numeric values in pred appear in retrieved text"""
    if not pred:
        return True
    pred_nums = set(m[0] for m in NUMERIC_RE.findall(pred))
    if not pred_nums:
        return False
    combined = " ".join(retrieved).lower()
    unsupported = [n for n in pred_nums if n not in combined]
    return len(unsupported) > 0


def answer_coverage(gold: str, retrieved: list[str]) -> float:
    """Coverage of answer keywords within retrieved chunks"""
    if not gold:
        return 1.0
    tokens = re.findall(r"[a-zA-Z0-9]+|[一-鿿]", gold.lower())
    tokens = [t for t in tokens if len(t) >= 2]
    if not tokens:
        return 1.0
    combined = " ".join(retrieved).lower()
    covered = sum(1 for t in tokens if t in combined)
    return covered / len(tokens)


def compute_metrics(items: list[dict]) -> dict:
    """Compute metrics for a group of (gold, pred, retrieved) tuples"""
    n = len(items)
    if n == 0:
        return {"n": 0}
    t_f1, pm, hal, cov = [], [], [], []
    for it in items:
        pred = it["pred"]
        gold = it["gold"]
        retrieved = it["retrieved"]
        t_f1.append(tuple_f1(
            extract_answer_tuples(pred, parameter=it.get("constraint_type", "")),
            extract_answer_tuples(gold, parameter=it.get("constraint_type", "")),
        ))
        pm.append(partial_match(pred, gold))
        hal.append(1 if is_hallucinated(pred, retrieved) else 0)
        cov.append(answer_coverage(gold, retrieved))
    mean_t = sum(t_f1) / n
    ci_t = bootstrap_ci(t_f1, n_bootstrap=2000) if n >= 5 else {"ci_lower": mean_t, "ci_upper": mean_t}
    return {
        "n": n,
        "Tuple-F1": mean_t,
        "Tuple-F1 CI": [ci_t["ci_lower"], ci_t["ci_upper"]],
        "Partial Match": sum(pm) / n,
        "Hallucination Rate": sum(hal) / n,
        "Answer Coverage": sum(cov) / n,
    }


def main():
    out_dir = RESULTS_DIR / "s3"
    out_dir.mkdir(parents=True, exist_ok=True)

    # Read T1 per-item outputs
    outputs_file = RESULTS_DIR / "s1" / "per_item_outputs.jsonl"
    if not outputs_file.exists():
        logger.error(f"{outputs_file} does not exist, please run T1 (run_llm_judge.py) first")
        sys.exit(1)

    outputs = [json.loads(l) for l in open(outputs_file, encoding="utf-8") if l.strip()]
    logger.info(f"Loaded {len(outputs)} outputs")

    # Group by (method, equipment_type)
    # Note: one item may belong to multiple equipment types, so accumulate
    grouped = defaultdict(list)
    for o in outputs:
        method = o["method"]
        for eq in o.get("equipment_types", []) or ["unspecified"]:
            grouped[(method, eq)].append(o)
        # Also accumulate an overall group
        grouped[(method, "overall")].append(o)

    # Compute metrics
    results = {}
    for (method, eq), items in grouped.items():
        metrics = compute_metrics(items)
        results.setdefault(method, {})[eq] = metrics

    # Save JSON
    json_path = out_dir / "s3a_cross_equipment.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    logger.info(f"Saved {json_path}")

    # Generate Markdown table
    md_lines = ["# S3a: Cross-Equipment Generalization Experiment\n"]
    md_lines.append("**Purpose**: Validate the generalization of StructStdRAG across different "
                    "equipment types. Grouped evaluation by the equipment_types field annotated "
                    "in the 88-item MIL-HDBK-470A test set.\n")

    equipment_types = ["aircraft_engine", "armored_vehicle", "naval_power", "overall"]
    methods = sorted(results.keys())

    # One table per metric
    for metric in ["Tuple-F1", "Hallucination Rate", "Answer Coverage"]:
        md_lines.append(f"\n## {metric} by Equipment Type\n")
        header = "| Method |" + "|".join(f" {EQUIPMENT_LABELS.get(e, e)} " for e in equipment_types) + "|"
        sep = "|" + "|".join(["---"] * (len(equipment_types) + 1)) + "|"
        md_lines.append(header)
        md_lines.append(sep)
        for method in methods:
            row = [method]
            for eq in equipment_types:
                val = results[method].get(eq, {})
                if "n" not in val or val["n"] == 0:
                    row.append("N/A")
                else:
                    v = val.get(metric, 0)
                    n = val["n"]
                    if metric == "Tuple-F1":
                        ci = val.get("Tuple-F1 CI", [v, v])
                        row.append(f"{v:.3f} ± [{ci[0]:.3f},{ci[1]:.3f}] (n={n})")
                    else:
                        row.append(f"{v:.3f} (n={n})")
            md_lines.append("| " + " | ".join(row) + " |")

    # Cross-method stability: std across equipment types
    md_lines.append("\n## Cross-Equipment Stability (Tuple-F1 Std Dev)\n")
    md_lines.append("| Method | Mean | Std Dev | CV |")
    md_lines.append("|---|---|---|---|")
    for method in methods:
        values = [results[method].get(eq, {}).get("Tuple-F1")
                  for eq in ["aircraft_engine", "armored_vehicle", "naval_power"]
                  if results[method].get(eq, {}).get("Tuple-F1") is not None]
        if len(values) >= 2:
            mean_v = sum(values) / len(values)
            var = sum((v - mean_v) ** 2 for v in values) / len(values)
            std = var ** 0.5
            cv = std / mean_v if mean_v else 0
            md_lines.append(f"| {method} | {mean_v:.3f} | {std:.3f} | {cv:.3f} |")

    md_path = out_dir / "s3a_cross_equipment.md"
    with open(md_path, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))
    logger.info(f"Saved {md_path}")

    # Print summary
    print("\n" + "=" * 80)
    print("S3a: Cross-Equipment Generalization Tuple-F1 Summary")
    print("=" * 80)
    for method in methods:
        row = f"{method:<20}"
        for eq in equipment_types:
            val = results[method].get(eq, {})
            if "n" in val and val["n"] > 0:
                row += f" {eq[:8]:>10}={val.get('Tuple-F1', 0):.3f}"
        print(row)


if __name__ == "__main__":
    main()
